-- Sprint 11-এ একটা RLS বাগ ঠিক করা হয়েছিল (20260730_fix_chairs_public_read_rls):
-- `chairs`-এ দুটো permissive SELECT পলিসি ছিল, একটার শর্ত `is_active = true`
-- আর অন্যটার শর্তহীন `true`। Postgres একই কমান্ডের permissive পলিসিগুলো OR
-- দিয়ে মেশায়, তাই শর্তহীনটা `is_active` বিধিনিষেধকে অকেজো করে দিচ্ছিল —
-- বন্ধ চেয়ারও যে কেউ দেখতে পেত। ঠিকভাবেই ওটা ড্রপ করা হয়।
--
-- **কিন্তু বদলে মালিকের জন্য কিছু দেওয়া হয়নি।** ফলে `chairs`-এ SELECT পলিসি
-- থেকে গেল একটাই: `is_active = true`। অর্থাৎ দোকানের মালিক **নিজের বন্ধ করা
-- চেয়ার নিজেই দেখতে পায় না**।
--
-- এর ফল একের পর এক:
--   * চেয়ার মুছতে গেলে (ইতিহাস থাকায়) সেটা পজ হয় — আর সাথে সাথেই অদৃশ্য
--   * ম্যানেজার পাতা বলে "কোনো চেয়ার নেই", যদিও সারিগুলো টেবিলে বহাল
--   * নতুন চেয়ারের `sort_order` বের করতে max(sort_order) দেখা হয় — লুকানো
--     সারিগুলো গণনায় আসে না, তাই ১ থেকেই শুরু হয় আর লুকানো চেয়ারের সাথে
--     সংঘর্ষ বাধে → **409**
--   * বোর্ডে ইনঅ্যাক্টিভ লেন দেখানোর কোডটাও অচল, কারণ চেয়ারটাই আসে না
--
-- ---------------------------------------------------------------------------
-- সমাধান
-- ---------------------------------------------------------------------------
-- মালিকের জন্য নিজের চেয়ার পড়ার পলিসি। পাবলিক দিকটা অপরিবর্তিত — বাইরের
-- কেউ এখনো শুধু চালু চেয়ারই দেখে, Sprint 11-এর গোপনীয়তা-সংশোধন অক্ষত।
drop policy if exists "chairs: owner read" on public.chairs;
create policy "chairs: owner read" on public.chairs
  for select to authenticated
  using (public.is_shop_owner(shop_id));

