-- * JSON ফেরত এলো  → ফাংশন ঠিক আছে; সমস্যা তাহলে অন্য কোথাও (অনুমতি, বা
--   ব্রাউজার পুরোনো বিল্ড চালাচ্ছে)। Vercel-এ রিডিপ্লয় হয়েছে কিনা দেখো।
--
-- * 'not authorized' → admin_users-এ ACTIVE কোনো সারি পাওয়া যায়নি, অথবা
--   claim বসেনি। উপরের সাব-কোয়েরিটা আলাদা করে চালিয়ে দেখো কী ফেরত দেয়।
--
-- * অন্য যেকোনো বার্তা → **এটাই আসল কারণ।** পুরো বার্তাটা কপি করে পাঠাও —
--   সাধারণত এমন দেখায়: column "x" does not exist / relation "y" does not
--   exist / permission denied for table z.
