-- ---------------------------------------------------------------------------
-- admin_shop_detail() কেন 400 দিচ্ছে — আসল বার্তাটা বের করা
-- ---------------------------------------------------------------------------
-- ব্রাউজার শুধু "400 Bad Request" দেখায়, ভেতরের Postgres বার্তাটা নয়। এই
-- স্ক্রিপ্টটা SQL এডিটরেই ফাংশনটা চালায়, তাই এরর হলে **পুরো বার্তাটা** চোখের
-- সামনে আসে — column does not exist, permission denied, যা-ই হোক।
--
-- একটা প্যাঁচ আছে: ফাংশনের প্রথম লাইনেই `is_platform_admin()` যাচাই, যেটা
-- `auth.uid()` দেখে। SQL এডিটরে তুমি `postgres`, তোমার কোনো auth.uid() নেই —
-- তাই সরাসরি চালালে সবসময় 'not authorized' আসবে, আসল সমস্যাটা ঢাকা পড়ে যাবে।
-- নিচের CTE-টা আগে একজন সত্যিকারের এডমিনের id-কে সেশনের claim হিসেবে বসায়,
-- তারপর ফাংশনটা ডাকে। claim-টা লেনদেন-স্থানীয় (তৃতীয় আর্গুমেন্ট `true`), তাই
-- কোয়েরি শেষ হলেই মুছে যায় — কিছু স্থায়ীভাবে বদলায় না।

-- ধাপ ০ — সবচেয়ে সস্তা চেষ্টা, আগে এটাই করো
-- মাইগ্রেশন চালানোর পর PostgREST-এর ফাংশন-ক্যাশ পুরোনো থেকে যেতে পারে, আর
-- তখন ঠিকঠাক ফাংশনও 400 দিতে পারে। এই এক লাইনে ক্যাশ রিলোড হয়; কিছু বদলায়
-- না, তাই নির্ভয়ে চালাও। এরপর ব্রাউজারে আবার দেখো।
notify pgrst, 'reload schema';

-- ধাপ ১ — কোন দোকানটা ভাঙছে, তার id নাও (ব্রাউজারের URL-এও আছে)
select id, name, status
  from public.shops
 order by created_at desc;

-- ধাপ ২ — নিচের id-টা বদলে ধাপ ১-এর একটা id বসাও, তারপর চালাও
with claim as (
  select set_config(
    'request.jwt.claims',
    json_build_object(
      'sub', (select user_id::text
                from public.admin_users
               where status = 'ACTIVE'
               order by case level when 'SUPER_ADMIN' then 0 else 1 end
               limit 1)
    )::text,
    true
  ) as jwt
)
select public.admin_shop_detail('8171a0d6-bcce-4e36-be57-0b16ee1ae1c0'::uuid)
  from claim;

